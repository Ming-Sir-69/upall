#!/usr/bin/env python3
"""Regenerate the PIXELART block in src/upall/icons.py from macOS .icns files.

Reads app icons via sips, downsamples them, decodes the PNG (stdlib zlib only)
and rewrites the marked block in icons.py. Runtime code never does this.
"""
from pathlib import Path
import binascii
import struct
import subprocess
import sys
import zlib

ROOT = Path(__file__).resolve().parents[1]
TARGET = ROOT / "src/upall/icons.py"

APPS = {
    "claude-desktop": "/Applications/Claude.app/Contents/Resources/electron.icns",
    "chatgpt": "/Applications/ChatGPT.app/Contents/Resources/icon-chatgpt.icns",
}
SIZE = 12  # square pixels; rendered as SIZE columns x SIZE//2 terminal rows


def decode_png(data):
    """Minimal 8-bit RGBA/RGB PNG decoder (non-interlaced)."""
    assert data[:8] == b"\x89PNG\r\n\x1a\n", "not a PNG"
    pos, width, height, color_type, raw = 8, 0, 0, 6, b""
    while pos < len(data):
        length, kind = struct.unpack(">I4s", data[pos:pos + 8])
        chunk = data[pos + 8:pos + 8 + length]
        pos += 12 + length
        if kind == b"IHDR":
            width, height, depth, color_type = struct.unpack(">IIBB", chunk[:10])
            assert depth == 8 and color_type in (2, 6), "need 8-bit RGB/RGBA"
        elif kind == b"IDAT":
            raw += chunk
        elif kind == b"IEND":
            break
    channels = 4 if color_type == 6 else 3
    stride = width * channels
    data = zlib.decompress(raw)
    pixels, previous, offset = [], bytearray(stride), 0
    for _ in range(height):
        filter_type = data[offset]
        row = bytearray(data[offset + 1:offset + 1 + stride])
        offset += 1 + stride
        for i in range(stride):
            left = row[i - channels] if i >= channels else 0
            up = previous[i]
            corner = previous[i - channels] if i >= channels else 0
            if filter_type == 1:
                row[i] = (row[i] + left) & 0xFF
            elif filter_type == 2:
                row[i] = (row[i] + up) & 0xFF
            elif filter_type == 3:
                row[i] = (row[i] + (left + up) // 2) & 0xFF
            elif filter_type == 4:
                p = left + up - corner
                distances = (abs(p - left), abs(p - up), abs(p - corner))
                row[i] = (row[i] + (left, up, corner)[distances.index(min(distances))]) & 0xFF
        pixels.append(row)
        previous = row
    def pixel(x, y):
        base = x * channels
        r, g, b = pixels[y][base:base + 3]
        alpha = pixels[y][base + 3] if channels == 4 else 255
        return (r, g, b) if alpha >= 128 else None
    return width, height, pixel


def pixelate(png_path):
    width, height, pixel = decode_png(png_path.read_bytes())
    rows = []
    for y in range(0, SIZE, 2):
        row = []
        for x in range(SIZE):
            def sample(yy):
                total = [0, 0, 0, 0]
                for sy in range(height // SIZE):
                    for sx in range(width // SIZE):
                        value = pixel(x * width // SIZE + sx, yy * height // SIZE + sy)
                        if value:
                            total[0] += value[0]; total[1] += value[1]; total[2] += value[2]; total[3] += 1
                return tuple(c // total[3] for c in total[:3]) if total[3] else None
            row.append((sample(y), sample(y + 1)))
        rows.append(row)
    return rows


def main():
    blocks = {}
    for role, icns in APPS.items():
        png = Path("/tmp") / f"upall-icon-{role}.png"
        subprocess.run(["sips", "-s", "format", "png", "-z", str(SIZE * 8), str(SIZE * 8), icns,
                        "--out", str(png)], check=True, capture_output=True)
        blocks[role] = pixelate(png)
    text = TARGET.read_text()
    begin, end = text.index("# BEGIN GENERATED"), text.index("# END GENERATED")
    generated = "# BEGIN GENERATED by tools/make_icons.py — do not edit by hand\nPIXELART = " + repr(blocks) + "\n"
    TARGET.write_text(text[:begin] + generated + text[end:])
    print(f"icons.py updated: {', '.join(blocks)}")


if __name__ == "__main__":
    sys.exit(main())
